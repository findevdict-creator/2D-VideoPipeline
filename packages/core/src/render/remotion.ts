import { spawn } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { bundle } from "@remotion/bundler";
import { renderMedia, renderStill, selectComposition } from "@remotion/renderer";
import { pipelineWebpackOverride } from "@pipeline/lib/webpack-override";
import type { VideoData } from "@pipeline/lib/types";
import type { StageContext } from "../context.js";
import { REPO_ROOT, renderPaths } from "./project.js";

const browser = (ctx: StageContext) => ctx.config.render.browserExecutable || null;

/**
 * Bundle this production's video with webpack. Returns the serve URL renders use.
 * With a scene id, bundles only that scene, so one broken scene cannot stop another from being checked.
 */
export async function bundleProduction(ctx: StageContext, sceneId?: string): Promise<string> {
  const r = renderPaths(ctx);
  let entryPoint = r.entry;
  if (sceneId) {
    entryPoint = path.join(r.dir, `check-${sceneId}.tsx`);
    await fs.writeFile(
      entryPoint,
      `// Generated by the pipeline to check one scene. Do not edit.
import { registerRoot } from "remotion";
import { makeRoot } from "@pipeline/lib";
import data from "./video-data.json";
import Scene from "../scenes/${sceneId}";

registerRoot(makeRoot(data as never, { ${sceneId}: Scene }));
`,
    );
  }
  return bundle({
    entryPoint,
    publicDir: r.publicDir,
    webpackOverride: pipelineWebpackOverride(REPO_ROOT),
    outDir: path.join(r.dir, sceneId ? `.bundle-${sceneId}` : ".bundle"),
  });
}

/** Type-check the scene files. Returns errors grouped by scene id ("_" for errors elsewhere). */
export async function typecheckScenes(ctx: StageContext): Promise<Record<string, string[]>> {
  const r = renderPaths(ctx);
  const tsc = path.join(REPO_ROOT, "node_modules", "typescript", "bin", "tsc");
  const output = await new Promise<string>((resolve, reject) => {
    const child = spawn(process.execPath, [tsc, "-p", r.tsconfig, "--pretty", "false"], { cwd: r.dir });
    let out = "";
    child.stdout.on("data", (d) => (out += d));
    child.stderr.on("data", (d) => (out += d));
    child.on("error", reject);
    child.on("close", () => resolve(out));
  });
  const errors: Record<string, string[]> = {};
  for (const line of output.split(/\r?\n/)) {
    if (!/error TS\d+/.test(line)) continue;
    // Errors in the generated files that name a scene (a bad default export, say) belong to that scene.
    const id = line.match(/[\\/]scenes[\\/](s\d{2})\.tsx/)?.[1] ?? line.match(/scenes[\\/](s\d{2})\b/)?.[1] ?? "_";
    (errors[id] ??= []).push(line.replace(/^.*[\\/]scenes[\\/]/, "scenes/").trim());
  }
  return errors;
}

/**
 * Pick the frames worth looking at in a scene: the last moments, then right after
 * each cue lands, then a third of the way in if there is room.
 */
export function framesToCheck(scene: VideoData["scenes"][number], fps: number, count: number): number[] {
  const last = scene.durationInFrames - 1;
  const end = Math.max(0, last - Math.round(fps * 0.3));
  const settle = Math.round(fps * 0.7);
  const cueFrames = [...new Set(scene.cues.map((c) => Math.min(last, c.startFrame + settle)))]
    .filter((f) => f !== end)
    .sort((a, b) => a - b);
  const picks = new Set<number>([end]);
  const room = count - 1;
  if (cueFrames.length <= room) {
    cueFrames.forEach((f) => picks.add(f));
  } else {
    // More cues than room: spread the picks across them.
    for (let i = 0; i < room; i++) picks.add(cueFrames[Math.round((i * (cueFrames.length - 1)) / Math.max(1, room - 1))]!);
  }
  if (picks.size < count) picks.add(Math.min(last, Math.round(scene.durationInFrames * 0.35)));
  return [...picks].sort((a, b) => a - b);
}

/** Render test frames of one scene to PNG. Returns the files, or throws with Remotion's error. */
export async function renderSceneStills(
  ctx: StageContext,
  serveUrl: string,
  sceneId: string,
  frames: number[],
): Promise<string[]> {
  const r = renderPaths(ctx);
  await fs.mkdir(r.stills, { recursive: true });
  for (const old of await fs.readdir(r.stills)) {
    if (old.startsWith(`${sceneId}-`)) await fs.rm(path.join(r.stills, old), { force: true });
  }
  const composition = await selectComposition({
    serveUrl,
    id: `Scene-${sceneId}`,
    browserExecutable: browser(ctx),
    logLevel: "error",
  });
  const out: string[] = [];
  for (const frame of frames) {
    const output = path.join(r.stills, `${sceneId}-f${String(frame).padStart(4, "0")}.png`);
    await renderStill({
      composition,
      serveUrl,
      frame,
      output,
      scale: ctx.config.render.stillScale,
      browserExecutable: browser(ctx),
      logLevel: "error",
    });
    out.push(output);
  }
  return out;
}

/** Render the full video to MP4. */
export async function renderVideo(
  ctx: StageContext,
  serveUrl: string,
  opts: { output: string; scale: number; crf: number; label: string },
) {
  const rc = ctx.config.render;
  const composition = await selectComposition({ serveUrl, id: "Video", browserExecutable: browser(ctx), logLevel: "error" });
  await fs.mkdir(path.dirname(opts.output), { recursive: true });
  let lastShown = -1;
  await renderMedia({
    composition,
    serveUrl,
    codec: rc.codec,
    crf: rc.codec === "prores" ? undefined : opts.crf,
    outputLocation: opts.output,
    scale: opts.scale,
    concurrency: rc.concurrency,
    browserExecutable: browser(ctx),
    logLevel: "error",
    onProgress: ({ progress }) => {
      const pct = Math.floor(progress * 10) * 10;
      if (pct !== lastShown) {
        lastShown = pct;
        ctx.log(`  ${opts.label}: ${pct}%`);
      }
    },
  });
  return { output: opts.output, durationSec: composition.durationInFrames / composition.fps, width: Math.round(composition.width * opts.scale), height: Math.round(composition.height * opts.scale) };
}
