import fs from "node:fs";
import path from "node:path";
import { renderStill, selectComposition } from "@remotion/renderer";
import type { VideoData } from "@pipeline/lib/types";
import type { ModelInfo } from "../assets/gltf.js";
import type { Asset } from "../store/assets.js";
import { projectPaths, type Project } from "../store/projects.js";
import type { Studio } from "../studio.js";
import { browser, bundleOnce, libHash, withGl } from "./remotion.js";

/** The same angles the library's ModelPreview draws, in the same order. */
const VIEWS = ["front right", "back left", "front", "top"];

export interface ModelPicture {
  file: string;
  caption: string;
}

/**
 * Pictures of a 3D model: from four sides, then each of its animations at its end, so
 * a person or an agent can see what the model is and what its animations do. Made once
 * per file and kept in the project's work folder.
 */
export async function modelPictures(studio: Studio, project: Project, asset: Asset, log: (m: string) => void = () => {}): Promise<ModelPicture[]> {
  const model = asset.meta.model as ModelInfo | undefined;
  if (!model) throw new Error(`Asset "${asset.label}" has not been read as a 3D model.`);
  const p = projectPaths(studio, project);
  const dir = path.join(p.work, "previews");
  const stem = path.join(dir, `${asset.sha256.slice(0, 16)}-${libHash(true)}`);
  const shots = [
    ...VIEWS.map((name, view) => ({ file: `${stem}-view${view + 1}.png`, caption: `${asset.label}, from the ${name}`, props: { view } })),
    ...model.animations.slice(0, 3).map((a, i) => ({
      file: `${stem}-anim${i + 1}.png`,
      caption: `${asset.label}, at the end of its animation "${a.name}" (${a.durationSec}s)`,
      props: { view: 0, animation: a.name, time: a.durationSec },
    })),
  ];
  if (shots.every((s) => fs.existsSync(s.file))) return shots.map(({ file, caption }) => ({ file, caption }));

  const entry = `// Generated by the studio. Do not edit.
import { registerRoot } from "remotion";
import { makeModelPreviewRoot } from "@pipeline/lib/three";

registerRoot(makeModelPreviewRoot());
`;
  const serveUrl = await bundleOnce(libHash(true), path.join(studio.workspaceDir, ".cache", `model-preview-${libHash(true)}`), entry, p.sharedComponents);
  const data: VideoData = {
    title: project.title,
    fps: project.fps,
    width: 1280,
    height: 960,
    style: project.settings.theme,
    transitionFrames: 0,
    captionSafeArea: 0,
    assetBase: await studio.assetBase(project.slug),
    scenes: [
      {
        id: `model-${asset.id}`,
        title: asset.label,
        narration: "",
        layout: "",
        visualDescription: "",
        elements: [],
        onScreenText: [],
        transitionIn: "cut",
        camera: "static",
        startFrame: 0,
        durationInFrames: 1,
        speechStartFrame: 0,
        speechEndFrame: 1,
        audio: null,
        cues: [],
        words: [],
        kind: "code",
        assets: {
          model: {
            src: asset.path,
            kind: "model",
            label: asset.label,
            width: null,
            height: null,
            durationSec: null,
            model: { size: model.size, center: model.center, parts: model.parts.map((x) => x.name), animations: model.animations.map((a) => ({ name: a.name, durationSec: a.durationSec })) },
          },
        },
      },
    ],
    captions: { enabled: false, fontSize: 54, position: "bottom", highlight: "accent", pages: [] },
    music: { src: null, volume: 0 },
  };
  fs.mkdirSync(dir, { recursive: true });
  await withGl(studio, true, log, async (chromiumOptions) => {
    const browserExecutable = browser(studio);
    for (const shot of shots) {
      const inputProps = { data, ...shot.props };
      const composition = await selectComposition({ serveUrl, id: "ModelPreview", inputProps, browserExecutable, chromiumOptions, logLevel: "error" });
      await renderStill({ composition, serveUrl, inputProps, output: shot.file, scale: 0.75, browserExecutable, chromiumOptions, logLevel: "error" });
    }
  });
  return shots.map(({ file, caption }) => ({ file, caption }));
}

/** The first picture of a model, if its pictures have been made. For thumbnails. */
export function modelThumbnail(studio: Studio, project: Project, asset: Asset): string | null {
  const file = path.join(projectPaths(studio, project).work, "previews", `${asset.sha256.slice(0, 16)}-${libHash(true)}-view1.png`);
  return fs.existsSync(file) ? file : null;
}
