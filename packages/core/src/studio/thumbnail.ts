import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { renderStill, selectComposition } from "@remotion/renderer";
import { checkSceneSource } from "../render/sceneCheck.js";
import { nowIso } from "./ids.js";
import { ffmpeg } from "./media/ffmpeg.js";
import { browser, bundleOnce, libHash, SCENE_IMPORTS, sharedHash, standaloneData, typecheckScene } from "./renderers/remotion.js";
import type { Studio } from "./studio.js";
import { getProject, projectPaths, type Project } from "./store/projects.js";

/** The size video sites ask for, and the size it is mostly seen at. */
export const THUMBNAIL_SIZE = { width: 1280, height: 720 } as const;
export const THUMBNAIL_SMALL = { width: 320, height: 180 } as const;

export interface Thumbnail {
  /** Counts up with every design saved. */
  version: number;
  /** The words on it, as its designer reports them. Empty when it has none. */
  text: string;
  /** One or two sentences on the idea: what it promises and why someone would click. */
  idea: string;
  /** Concepts the designer considered and did not draw, a sentence each: candidates for a second thumbnail to test. */
  others?: string[];
  /** Relative to the project folder. Missing when it has not been drawn (no browser). */
  image: string | null;
  small: string | null;
  source: string;
  updatedAt: string;
}

export function thumbnailPaths(studio: Studio, project: Pick<Project, "slug">) {
  const p = projectPaths(studio, project);
  const dir = p.at("thumbnail");
  return { dir, source: path.join(dir, "thumbnail.tsx"), meta: path.join(dir, "thumbnail.json"), work: path.join(p.work, "thumbnail") };
}

export function getThumbnail(studio: Studio, projectId: string): Thumbnail | undefined {
  const project = getProject(studio, projectId);
  const t = thumbnailPaths(studio, project);
  if (!fs.existsSync(t.meta)) return undefined;
  try {
    const meta = JSON.parse(fs.readFileSync(t.meta, "utf8")) as Thumbnail;
    const p = projectPaths(studio, project);
    const there = (rel: string | null) => (rel && fs.existsSync(p.abs(rel)) ? rel : null);
    return { ...meta, image: there(meta.image), small: there(meta.small) };
  } catch {
    return undefined;
  }
}

/** Problems that stop a thumbnail's code from being drawn. Empty when it is fine. */
export async function checkThumbnail(studio: Studio, project: Project, code: string): Promise<string[]> {
  const p = projectPaths(studio, project);
  const problems = checkSceneSource(code, { allowed: SCENE_IMPORTS["remotion-2d"], allowedPrefixes: ["@shared/"] });
  for (const hook of ["useCurrentFrame", "useCueFrame", "useCueAppear", "useCues", "useAppear", "useBetween", "useLoop", "spring"]) {
    if (new RegExp(`\\b${hook}\\s*\\(`).test(code)) problems.push(`A thumbnail is one still picture, so ${hook} has no place in it. Draw everything in its final state.`);
  }
  if (problems.length) return problems;
  const t = thumbnailPaths(studio, project);
  const probe = path.join(t.work, "check", "thumbnail.tsx");
  fs.mkdirSync(path.dirname(probe), { recursive: true });
  fs.writeFileSync(probe, code);
  try {
    return await typecheckScene(probe, path.dirname(probe), p.sharedComponents);
  } finally {
    fs.rmSync(path.dirname(probe), { recursive: true, force: true });
  }
}

/** Draw a thumbnail's code at full size and at the size it is seen at in a list. */
export async function renderThumbnail(studio: Studio, project: Project, sourceFile: string, image: string, small: string): Promise<void> {
  const p = projectPaths(studio, project);
  const t = thumbnailPaths(studio, project);
  const code = fs.readFileSync(sourceFile, "utf8");
  const entry = `// Generated by the studio. Do not edit.
import { registerRoot } from "remotion";
import { makeSceneRoot } from "@pipeline/lib";
import Thumbnail from ${JSON.stringify(sourceFile.split(path.sep).join("/"))};

registerRoot(makeSceneRoot(Thumbnail));
`;
  const key = createHash("sha1").update(JSON.stringify([code, libHash(), sharedHash(code, p.sharedComponents)])).digest("hex").slice(0, 16);
  const serveUrl = await bundleOnce(key, path.join(t.work, "bundle"), entry, p.sharedComponents);
  // A thumbnail is clean whatever the video's look: wobbling lines read as blur at stamp size.
  const base = standaloneData(project, "thumbnail", project.title, THUMBNAIL_SIZE);
  const data = { ...base, style: { ...base.style, look: "clean" as const }, assetBase: await studio.assetBase(project.slug) };
  const inputProps = { data };
  const browserExecutable = browser(studio);
  const composition = await selectComposition({ serveUrl, id: "Scene", inputProps, browserExecutable, logLevel: "error" });
  fs.mkdirSync(path.dirname(image), { recursive: true });
  await renderStill({ composition, serveUrl, inputProps, frame: 0, output: image, scale: 1, browserExecutable, logLevel: "error" });
  await renderStill({ composition, serveUrl, inputProps, frame: 0, output: small, scale: THUMBNAIL_SMALL.width / THUMBNAIL_SIZE.width, browserExecutable, logLevel: "error" });
}

export interface SavedThumbnail {
  thumbnail: Thumbnail;
  /** Full paths of the two pictures, when they were drawn. */
  image?: string;
  small?: string;
  /** Why it could not be drawn, when the code is saved but no picture came out. */
  drawProblem?: string;
}

/**
 * Save a thumbnail design and draw it. Each save replaces the design; the picture gets a
 * new file name, so a browser never shows the old one.
 */
export async function saveThumbnail(studio: Studio, projectId: string, input: { code: string; text?: string; idea?: string; others?: string[] }): Promise<SavedThumbnail> {
  const project = getProject(studio, projectId);
  const p = projectPaths(studio, project);
  const t = thumbnailPaths(studio, project);
  const version = (getThumbnail(studio, projectId)?.version ?? 0) + 1;
  fs.mkdirSync(t.dir, { recursive: true });
  fs.writeFileSync(t.source, input.code);
  const image = path.join(t.dir, `thumbnail-v${version}.png`);
  const small = path.join(t.dir, `thumbnail-v${version}-small.png`);
  let drawProblem: string | undefined;
  // The stand-in runner is for trying the flow without a browser, so it goes without pictures unless one is set.
  const draws = !(studio.config.runner === "mock" && !studio.config.render.browserExecutable);
  if (draws) {
    try {
      await renderThumbnail(studio, project, t.source, image, small);
    } catch (err) {
      drawProblem = (err as Error).message.split("\n")[0];
    }
  }
  const drawn = draws && !drawProblem;
  const thumbnail: Thumbnail = {
    version,
    text: input.text?.trim() ?? "",
    idea: input.idea?.trim() ?? "",
    others: (input.others ?? []).map((o) => o.trim()).filter(Boolean).slice(0, 3),
    image: drawn ? p.rel(image) : null,
    small: drawn ? p.rel(small) : null,
    source: p.rel(t.source),
    updatedAt: nowIso(),
  };
  fs.writeFileSync(t.meta, JSON.stringify(thumbnail, null, 2) + "\n");
  if (drawn) {
    for (const name of fs.readdirSync(t.dir)) if (/^thumbnail-v\d+(-small)?\.png$/.test(name) && !name.startsWith(`thumbnail-v${version}`)) fs.rmSync(path.join(t.dir, name), { force: true });
  }
  studio.emit("project.updated", { projectId });
  return { thumbnail, ...(drawn ? { image, small } : {}), ...(drawProblem ? { drawProblem } : {}) };
}

/** The designed thumbnail as a JPEG at `output`, for an export package. False when there is none to copy. */
export async function copyThumbnail(studio: Studio, projectId: string, output: string): Promise<boolean> {
  const thumbnail = getThumbnail(studio, projectId);
  if (!thumbnail?.image) return false;
  const p = projectPaths(studio, getProject(studio, projectId));
  await ffmpeg(["-i", p.abs(thumbnail.image), "-frames:v", "1", "-q:v", "2", output]);
  return true;
}
